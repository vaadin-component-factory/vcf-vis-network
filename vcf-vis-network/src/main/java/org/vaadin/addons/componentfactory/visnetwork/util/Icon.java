package org.vaadin.addons.componentfactory.visnetwork.util;


import com.fasterxml.jackson.annotation.JsonProperty;

public class Icon {
    private Face face = Face.FontAwesome;
    private String code;
    private int size = 50;
    private String color = "#2B7CE9";

    public enum Face{
        @JsonProperty("FontAwesome")
        FontAwesome,
        @JsonProperty("Ionicons")
        Ionicons
    }

    public Face getFace() {
        return face;
    }

    public void setFace(Face face) {
        this.face = face;
    }

    public String getCode() {
        return code;
    }

    public void setCode(String code) {
        this.code = code;
    }

    public int getSize() {
        return size;
    }

    public void setSize(int size) {
        this.size = size;
    }

    public String getColor() {
        return color;
    }

    public void setColor(String color) {
        this.color = color;
    }
}
